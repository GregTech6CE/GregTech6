    /**
     * GT6's shared-role covers: the vanilla redstone torch/repeater ({@code GT_API:799-802}) and the
     * compact electric pump/conveyor/robot arm ({@code MultiItemTechnological:50-53}) are covers
     * themselves, and the programmed circuit is the tag selector ({@code ItemIntegratedCircuit:87}).
     * The port must attach those items directly — no separate cover item, and no recipe for one.
     */
    @GameTest(template = "test_blueprint_empty", timeoutTicks = 400)
    public static void vanillaBlocksAndComponentsDoubleAsCovers(GameTestHelper h) {
        var pump = new ItemStack(GTTechnological.get("compact_electric_pump_lv"));
        var conveyor = new ItemStack(GTTechnological.get("compact_electric_conveyor_ulv"));
        var arm = new ItemStack(GTTechnological.get("compact_robot_arm_uv"));
        var circuit = new ItemStack(GTTechnological.selectorTag(7));
        var torch = new ItemStack(net.minecraft.world.item.Items.REDSTONE_TORCH);
        var repeater = new ItemStack(net.minecraft.world.item.Items.REPEATER);

        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.behavior(torch)
                .equals(com.gregtech.gregtech.content.cover.CoverItems.REDSTONE_TORCH),
                "a vanilla redstone torch is a redstone torch cover");
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.behavior(repeater)
                .equals(com.gregtech.gregtech.content.cover.CoverItems.REDSTONE_REPEATER),
                "a vanilla repeater is a redstone repeater cover");
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.behavior(pump)
                .equals(com.gregtech.gregtech.content.cover.CoverItems.PUMP), "a compact pump is a pump cover");
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.behavior(circuit)
                .equals(com.gregtech.gregtech.content.cover.CoverItems.TAG_SELECTOR), "a circuit selects tags");
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.selectorTag(circuit) == 7,
                "the circuit's variant is the selected tag");
        h.assertTrue(!com.gregtech.gregtech.content.cover.CoverItems.isCover(new ItemStack(Items.IRON_INGOT)),
                "an ordinary item is not a cover");

        // GT6 tiers: CoverPump(250 << 2i) mB per 20 ticks, CoverConveyor/RobotArm(512 >> i) ticks.
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.pumpThroughput(pump) == 1000,
                "LV pump moves 1000 mB per operation");
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.itemInterval(conveyor) == 512,
                "ULV conveyor moves a stack every 512 ticks");
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.itemInterval(arm) == 2,
                "UV robot arm moves a stack every 2 ticks");

        // ... and the machine accepts them on a face, which is what makes them covers.
        var block = com.gregtech.gregtech.api.machine.MachineRegistry.basicMachines().get(0).get();
        BlockPos pos = new BlockPos(4, 3, 4);
        h.setBlock(pos, Blocks.AIR);
        h.setBlock(pos, block);
        var machine = (com.gregtech.gregtech.blockentity.machine.BasicMachineBlockEntity)
                h.getLevel().getBlockEntity(h.absolutePos(pos));
        h.assertTrue(machine.attachCover(Direction.NORTH, pump), "machine face accepts a compact pump");
        h.assertTrue(com.gregtech.gregtech.content.cover.CoverItems.behavior(machine.getCover(Direction.NORTH))
                        .equals(com.gregtech.gregtech.content.cover.CoverItems.PUMP),
                "the attached pump keeps its cover behaviour");
        h.assertTrue(machine.removeCover(Direction.NORTH).is(pump.getItem()), "crowbar returns the component");
        h.assertTrue(!machine.attachCover(Direction.SOUTH, torch), "machine rejects a wire-only redstone torch");
        h.assertTrue(!machine.hasRedstoneCover(), "rejected torch does not become a machine cover");
        h.succeed();
    }

    /**
     * The filled cells come from the Canning Machine (GT6 {@code MultiItemTechnological:462-482}
     * declares each filled cell as a fluid container), so each empty cell needs exactly one row and
     * that row must deliver the original's electrolyte amount.
     */
    @GameTest(template = "test_blueprint_empty", timeoutTicks = 300)
    public static void filledBatteryCellsComeFromTheCanner(GameTestHelper h) {
        String[][] expected = {
                {"lead_acid_cell_empty", "lead_acid_cell_filled", "2000"},
                {"alkaline_button_cell_empty", "alkaline_button_cell_filled", "1000"},
                {"nickel_cadmium_cell_empty", "nickel_cadmium_cell_filled", "1000"},
                {"lithium_cobalt_cell_empty", "lithium_cobalt_cell_filled", "2000"},
                {"lithium_manganese_cell_empty", "lithium_manganese_cell_filled", "2000"}};
        h.assertTrue(com.gregtech.gregtech.content.recipe.BatteryCellRecipes.skipped().isEmpty(),
                "no battery cell row was skipped: "
                        + com.gregtech.gregtech.content.recipe.BatteryCellRecipes.skipped());
        for (String[] row : expected) {
            ItemStack empty = stack(row[0]);
            h.assertTrue(!empty.isEmpty(), "empty cell is registered: " + row[0]);
            int found = 0;
            for (com.gregtech.gregtech.api.recipe.Recipe recipe
                    : com.gregtech.gregtech.data.MachineRecipeMaps.Canner.mRecipeList) {
                if (recipe.mInputs.length == 0 || !recipe.mInputs[0].is(empty.getItem())) continue;
                found++;
                h.assertTrue(recipe.mOutputs.length == 1 && recipe.mOutputs[0].is(stack(row[1]).getItem()),
                        row[0] + " cans into " + row[1]);
                h.assertTrue(recipe.mFluidInputs.length == 1
                                && recipe.mFluidInputs[0].getAmount() == Integer.parseInt(row[2]),
                        row[0] + " needs " + row[2] + " mB of electrolyte");
            }
            h.assertTrue(found == 1, row[0] + " has exactly one canning row; got " + found);
        }
        h.succeed();
    }

    private static ItemStack stack(String id) {
        Item item = ForgeRegistries.ITEMS.getValue(
                ResourceLocation.fromNamespaceAndPath("gregtech", id));
        return item == null ? ItemStack.EMPTY : new ItemStack(item);
    }
