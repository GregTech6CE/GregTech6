    /** Recipe directories/ids the generated batch owns. */
    private static boolean isBatchRecipe(ResourceLocation id) {
        if (!id.getNamespace().equals("gregtech")) return false;
        String path = id.getPath();
        if (path.startsWith("hand_covers/") || path.startsWith("hand_components/")) return true;
        if (!path.startsWith("logistics/")) return false;
        String name = path.substring("logistics/".length());
        return name.startsWith("logistics_display_cpu_") || name.startsWith("logistics_cycle_")
                || name.startsWith("filtered_logistics_") || name.startsWith("generic_logistics_")
                || name.equals("logistics_dump_bus_item");
    }

    private static List<Recipe<?>> batch(GameTestHelper helper) {
        List<Recipe<?>> batch = new ArrayList<>();
        for (Recipe<?> recipe : helper.getLevel().getRecipeManager().getRecipes()) {
            if (isBatchRecipe(recipe.getId())) batch.add(recipe);
        }
        return batch;
    }

    private static TransientCraftingContainer grid() {
        var menu = new AbstractContainerMenu(null, 0) {
            public ItemStack quickMoveStack(net.minecraft.world.entity.player.Player player, int slot) {
                return ItemStack.EMPTY;
            }

            public boolean stillValid(net.minecraft.world.entity.player.Player player) {
                return true;
            }
        };
        return new TransientCraftingContainer(menu, 3, 3);
    }

    /** GT tools have to be usable copies, exactly like a player would hold them. */
    private static ItemStack usable(ItemStack stack) {
        if (stack.getItem() instanceof GTToolItem) {
            return GTToolItem.create(GTToolHelper.getType(stack),
                    com.gregtech.gregtech.content.material.Materials.Steel,
                    com.gregtech.gregtech.api.material.GTMaterialRegistry.get("Wood"));
        }
        return stack.copy();
    }

    /** Every item the batch promised to make obtainable is produced by some recipe. */
    @GameTest(template = "test_blueprint_empty", timeoutTicks = 400)
    public static void batchItemsAreCraftable(GameTestHelper h) {
        Set<String> produced = new TreeSet<>();
        for (Recipe<?> recipe : h.getLevel().getRecipeManager().getRecipes()) {
            ItemStack result;
            try {
                result = recipe.getResultItem(h.getLevel().registryAccess());
            } catch (RuntimeException e) {
                continue;
            }
            if (result != null && !result.isEmpty()) {
                ResourceLocation key = ForgeRegistries.ITEMS.getKey(result.getItem());
                if (key != null) produced.add(key.getPath());
            }
        }
        List<String> missing = new ArrayList<>();
        for (String id : BATCH_OUTPUTS) if (!produced.contains(id)) missing.add(id);
        h.assertTrue(missing.isEmpty(), "GT6 hand recipes missing for: " + missing);

        // ... and no other cover/USB/logistics/selector item is left without a recipe either.
        List<String> leftovers = new ArrayList<>();
        for (var entry : GTTechnological.all()) {
            if (!entry.isPresent()) continue;
            ResourceLocation key = ForgeRegistries.ITEMS.getKey(entry.get());
            if (key == null) continue;
            String id = key.getPath();
            boolean inBatchFamily = id.startsWith("cover") || id.startsWith("usb")
                    || id.contains("logistics") || id.startsWith("integrated_circuit_")
                    || id.equals("drain") || id.equals("air_vent") || id.equals("pressure_value");
            if (inBatchFamily && !produced.contains(id)) leftovers.add(id);
        }
        h.assertTrue(leftovers.isEmpty(), "cover/USB/logistics items still without a recipe: " + leftovers);
        h.succeed();
    }

    /** No generated row may contain an ingredient that matches nothing (an empty tag / bad id). */
    @GameTest(template = "test_blueprint_empty", timeoutTicks = 400)
    public static void batchIngredientsResolve(GameTestHelper h) {
        List<Recipe<?>> batch = batch(h);
        h.assertTrue(batch.size() == 71, "71 generated hand recipes loaded; got " + batch.size());
        for (Recipe<?> recipe : batch) {
            for (var ingredient : recipe.getIngredients()) {
                if (ingredient.isEmpty()) continue;             // pattern space
                h.assertTrue(ingredient.getItems().length > 0,
                        "ingredient of " + recipe.getId() + " matches no item");
            }
        }
        h.succeed();
    }

    /**
     * Each row must craft exactly once: building the grid from a recipe's own ingredients may match
     * that recipe only. This is what catches the mirror-image collisions GT6 avoids by not setting
     * {@code CR.MIR}.
     */
    @GameTest(template = "test_blueprint_empty", timeoutTicks = 600)
    public static void batchPatternsAreUnambiguous(GameTestHelper h) {
        List<Recipe<?>> batch = batch(h);
        List<Recipe<?>> all = new ArrayList<>(h.getLevel().getRecipeManager().getRecipes());
        TreeMap<String, String> collisions = new TreeMap<>();
        int checked = 0;
        for (Recipe<?> recipe : batch) {
            if (!(recipe instanceof net.minecraft.world.item.crafting.ShapedRecipe shaped)) continue;
            TransientCraftingContainer grid = grid();
            for (int y = 0; y < shaped.getHeight(); y++) {
                for (int x = 0; x < shaped.getWidth(); x++) {
                    var ingredient = shaped.getIngredients().get(x + y * shaped.getWidth());
                    if (!ingredient.isEmpty()) {
                        ItemStack[] options = ingredient.getItems();
                        h.assertTrue(options.length > 0, "ingredient of " + shaped.getId() + " matches no item");
                        grid.setItem(x + y * 3, usable(options[0]));
                    }
                }
            }
            h.assertTrue(shaped.matches(grid, h.getLevel()), "generated pattern works: " + shaped.getId());
            List<String> also = new ArrayList<>();
            for (Recipe<?> other : all) {
                if (other == shaped || !(other instanceof net.minecraft.world.item.crafting.ShapedRecipe candidate)) {
                    continue;
                }
                if (candidate.matches(grid, h.getLevel())) also.add(other.getId().toString());
            }
            if (!also.isEmpty()) collisions.put(shaped.getId().toString(), also.toString());
            checked++;
        }
        h.assertTrue(collisions.isEmpty(), "generated patterns collide: " + collisions);
        // 57 of the 71 generated rows are shaped (6 covers, 12 USB parts, 14 logistics buses,
        // 25 selector circuits); the other 14 are the shapeless logistics variant cycle.
        h.assertTrue(checked == 57, "shaped rows checked for collisions: " + checked);
        h.succeed();
    }

    /**
     * GT6's rows do not mirror unless they say so ({@code CR.java:161-163}: {@code DEF = BUF|NO_REM},
     * {@code DEF_MIR = DEF|MIR}); 1.20.1 mirrors shaped recipes by default. Every
     * {@code gregtech:tool_shaped} recipe therefore has to carry the original's answer
     * ({@code tools/apply_recipe_mirror_flags.py} writes it from
     * {@code docs/gt6-crafting-mirror-flags.json}); the census found no port row that opts in
     * (93 of GT6's 1188 rows do; this port registers the Blue Spruce slab from
     * {@code Loader_Recipes_Woods.java:270}, which uses {@code CR.DEF_NCC_MIR}).
     *
     * <p>The pattern itself is reported per row ({@code docs/tool-shaped-mirror-report.json}, read
     * back by {@code tools/report_tool_shaped_mirror.py}) so the flag can be audited against the
     * shape; the collision check — what mirroring actually breaks in game — is
     * {@link #batchPatternsAreUnambiguous}.</p>
     */
    @GameTest(template = "test_blueprint_empty", timeoutTicks = 600)
    public static void toolShapedRecipesDoNotMirrorUnlessTheOriginalDid(GameTestHelper h) {
        int checked = 0;
        int asymmetric = 0;
        int unresolvedIngredients = 0;
        java.util.List<String> mirroring = new java.util.ArrayList<>();
        for (Recipe<?> recipe : h.getLevel().getRecipeManager().getRecipes()) {
            if (!recipe.getId().getNamespace().equals("gregtech")) continue;
            if (!(recipe instanceof com.gregtech.gregtech.recipe.ToolShapedRecipe tool)) continue;
            // Rows injected at runtime (hand recipes, the GT6 masonry patterns) state their own flag in
            // code and are audited by their own tests; this rule is about the data-pack rows the
            // mirror-flag tool writes.
            if (com.gregtech.gregtech.loaders.Loader_StoneCraftingRecipes.registeredIds()
                    .contains(tool.getId().toString())) continue;
            if (com.gregtech.gregtech.loaders.Loader_HandToolCraftingRecipes.registeredIds()
                    .contains(tool.getId().toString())) continue;
            if (com.gregtech.gregtech.loaders.Loader_ToolCraftingRecipes.registeredIds()
                    .contains(tool.getId().toString())) continue;
            checked++;
            if (tool.allowMirror()) mirroring.add(tool.getId().toString());
            int width = tool.getWidth();
            int height = tool.getHeight();
            boolean symmetric = true;
            for (int y = 0; y < height; y++) {
                for (int x = 0; x < width; x++) {
                    var ingredient = tool.getIngredients().get(x + y * width);
                    var mirrored = tool.getIngredients().get(width - 1 - x + y * width);
                    if (ingredient.isEmpty() != mirrored.isEmpty()) symmetric = false;
                    if (!ingredient.isEmpty() && ingredient.getItems().length == 0) unresolvedIngredients++;
                }
            }
            if (!symmetric) asymmetric++;
        }
        // 668 data-pack rows (the runtime hand/stone rows state their flag in code and are audited by
        // their own tests, so they are excluded above).
        h.assertTrue(checked >= 600, "tool_shaped recipes checked: " + checked);
        h.assertTrue(mirroring.equals(java.util.List.of("gregtech:wood/slab_bluespruce")),
                "only the GT6 CR.DEF_NCC_MIR Blue Spruce slab row mirrors: " + mirroring);
        // 113 of those 668 data-pack rows have a pattern that is not mirror-symmetric, i.e. exactly the
        // rows where the flag is observable at all (183 counting the runtime hand/stone rows, which
        // state their own flag in code).
        h.assertTrue(asymmetric >= 100, "asymmetric patterns present: " + asymmetric);
        h.assertTrue(unresolvedIngredients == 0,
                "ingredients that match no item: " + unresolvedIngredients);
        h.succeed();
    }

    /** Shape report for the mirror rule: written so the pattern of every row can be inspected. */
    @GameTest(template = "test_blueprint_empty", timeoutTicks = 400)
    public static void mirrorRuleReportIsWritten(GameTestHelper h) {
        var report = new java.util.TreeMap<String, com.google.gson.JsonObject>();
        int unbuildable = 0;
        int asymmetric = 0;
        for (Recipe<?> recipe : h.getLevel().getRecipeManager().getRecipes()) {
            if (!recipe.getId().getNamespace().equals("gregtech")) continue;
            if (!(recipe instanceof com.gregtech.gregtech.recipe.ToolShapedRecipe tool)) continue;
            int width = tool.getWidth();
            int height = tool.getHeight();
            StringBuilder shape = new StringBuilder();
            boolean buildable = true;
            boolean symmetric = true;
            int unresolved = 0;
            for (int y = 0; y < height; y++) {
                for (int x = 0; x < width; x++) {
                    var ingredient = tool.getIngredients().get(x + y * width);
                    var mirrored = tool.getIngredients().get(width - 1 - x + y * width);
                    boolean empty = ingredient.isEmpty();
                    boolean emptyMirror = mirrored.isEmpty();
                    if (empty != emptyMirror) symmetric = false;
                    if (empty) {
                        shape.append('.');
                        continue;
                    }
                    if (ingredient.getItems().length == 0) {
                        buildable = false;
                        unresolved++;
                        shape.append('?');
                        continue;
                    }
                    shape.append('X');
                }
                shape.append('/');
            }
            if (!buildable) unbuildable++;
            else if (!symmetric) asymmetric++;
            var entry = new com.google.gson.JsonObject();
            entry.addProperty("mirror", tool.allowMirror());
            entry.addProperty("size", width + "x" + height);
            entry.addProperty("shape", shape.toString());
            entry.addProperty("symmetric", symmetric);
            entry.addProperty("unresolvedIngredients", unresolved);
            report.put(tool.getId().toString(), entry);
        }
        try {
            java.nio.file.Files.writeString(
                    java.nio.file.Path.of("../../docs/tool-shaped-mirror-report.json"),
                    new com.google.gson.GsonBuilder().setPrettyPrinting().create().toJson(report));
        } catch (java.io.IOException e) {
            h.fail("cannot write docs/tool-shaped-mirror-report.json: " + e);
            return;
        }
        h.assertTrue(report.size() >= 1180, "rows reported: " + report.size()
                + " (asymmetric " + asymmetric + ", unbuildable " + unbuildable + ")");
        h.succeed();
    }
