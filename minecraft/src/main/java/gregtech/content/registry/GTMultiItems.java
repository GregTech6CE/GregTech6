package gregtech.content.registry;

import static gregtech.engine.mod.GregTechIdentity.REGISTRY_NAMESPACE;

import gregtech.content.item.MultiBehaviorItem;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.Map;
import net.minecraft.world.item.Item;

/**
 * GT6 MultiItem categories (random tools, bottles, food, bumblebees) registered as
 * display items — behaviors (food stats, bee genetics) arrive with their systems.
 * Data comes from {@link GTMultiItemsGen} (transpiled from the GT6 sources).
 */
public final class GTMultiItems {
    private static final Map<String, RegisteredItem<Item>> BY_ID = new LinkedHashMap<>();

    private GTMultiItems() {}

    public static Collection<RegisteredItem<Item>> all() {
        return BY_ID.values();
    }

    public static void register(ContentRegistrar registrar) {
        if (!BY_ID.isEmpty()) throw new IllegalStateException("Multi items registered twice");
        String[] entries = GTMultiItemsGen.ENTRIES;
        for (int i = 0; i + 3 < entries.length; i += 4) {
            String id = entries[i];
            String name = entries[i + 1];
            String category = entries[i + 2];
            // GT6's own food numbers (MultiItemFood's FoodStat tables) instead of one blanket
            // placeholder. GTFoodItems.itemProperties falls back to the plain 64-stack properties for
            // the 59 rows that are display-only in GT6 as well, so nothing stops being edible by
            // accident - and `cans` uses the separate original MultiItemCans table.
            final Item.Properties props = "food".equals(category) || "cans".equals(category)
                    ? gregtech.content.food.GTFoodItems.itemProperties(id)
                    : new Item.Properties().stacksTo(64);
            BY_ID.put(id, registrar.item(REGISTRY_NAMESPACE, id, () -> create(id, name, category, props)));
        }
        registerWoodenBuckets(registrar);
        registerPaintSprays(registrar);
        // GT6's Dusty Guide Book (MultiItemBooks:67, addItem 32765) opens the gt.books table. The port
        // registers it by hand: it is the only MultiItemBooks entry the loot chain needs, and
        // transpile_gt6_multiitems.py has a HAND_REGISTERED set so a later "books" category never
        // emits this id twice. Its assets come from tools/generate_guide_book_assets.py.
        BY_ID.put("dusty_guide_book", registrar.item(REGISTRY_NAMESPACE, "dusty_guide_book",
                () -> new gregtech.content.loot.LootBagItem(new Item.Properties().stacksTo(64), "gt.books")));
        // GT6's Dusty Material Dictionary (MultiItemBooks:68, addItem 32766) rolls gt.matdicts, the
        // table GTLootTables builds from the registered materials. Assets come from
        // tools/generate_material_dictionary_assets.py.
        BY_ID.put("dusty_material_dictionary", registrar.item(REGISTRY_NAMESPACE, "dusty_material_dictionary",
                () -> new gregtech.content.loot.LootBagItem(new Item.Properties().stacksTo(64), "gt.matdicts")));
        // GT6's Loot Bottle (MultiItemBottles:367 "Clouded Bottle", addItem 32761) opens gt.bottles —
        // the last GT table the port had deferred; assets from tools/generate_loot_bottle_assets.py.
        BY_ID.put("loot_bottle", registrar.item(REGISTRY_NAMESPACE, "loot_bottle",
                () -> new gregtech.content.loot.LootBagItem(new Item.Properties().stacksTo(64), "gt.bottles")));
    }

    private static Item create(String id, String name, String category, Item.Properties props) {
        if (gregtech.content.storage.SafeLockRules.isKey(id))
            return new gregtech.content.item.GTDungeonKeyItem(props);
        if ("cans".equals(category)) return new gregtech.content.item.CannedFoodItem(id, name, props);
        if (id.equals("geiger_counter")) return new gregtech.content.item.GeigerCounterItem();
        //.C: GT6's drink bottles (MultiItemBottles) are the 250 mB portion of their fluid, so
        // they get a drinking item instead of the plain display item. The mapping is generated by
        // tools/extract_gt6_bottles.py; ids whose fluid the port does not have keep the plain item.
        String bottleFluid = gregtech.content.food.GTBottles.fluidKeyOf(id);
        if (bottleFluid != null && !"food".equals(category) && !"cans".equals(category))
            return new gregtech.content.item.BottleItem(
                    bottleFluid, gregtech.content.food.GTBottles.amountOf(id), props);
        return switch (id) {
            case "printed_pages", "many_printed_pages" ->
                    new gregtech.content.item.PrintedPagesItem(id.equals("many_printed_pages"), props);
            case "portable_scanner", "portable_cropnalyzer", "debug_scanner" ->
                    new gregtech.content.item.ScannerItem(name, gregtech.engine.tool.ScannerEnergyRules.forItem(id), props);
            case "radaway" -> new gregtech.content.item.RadawayItem();
            case "empty_wax_pill" -> new MultiBehaviorItem(name, new Item.Properties().food(
//? if >=1.21.1 {
                    /*new net.minecraft.world.food.FoodProperties.Builder().nutrition(0).saturationModifier(0).alwaysEdible().build()
*///?} else {
                    new net.minecraft.world.food.FoodProperties.Builder().nutrition(0).saturationMod(0).alwaysEat().build()
//?}
            ));
            // The four GT6 loot bags: right-click a block to open them and get GT's own loot
            // tables (MultiItemRandomTools:583-586, Behavior_Drop_Loot).
            case "bagged_sapling" -> new gregtech.content.loot.LootBagItem(props, "gt.saplings");
            case "seed_pouch" -> new gregtech.content.loot.LootBagItem(props, "gt.seeds");
            case "gem_pouch" -> new gregtech.content.loot.LootBagItem(props, "gt.flawless", "gt.gems", "gt.gems");
            case "loot_pouch" -> new gregtech.content.loot.LootBagItem(props, "gt.misc");
            default -> new MultiBehaviorItem(name, props);
        };
    }

    private static void registerWoodenBuckets(ContentRegistrar registrar) {
        for (var band : gregtech.content.tool.WoodenBucketCatalog.BANDS)
            for (var content : gregtech.content.tool.WoodenBucketCatalog.CONTENTS) {
                String id = gregtech.content.tool.WoodenBucketCatalog.itemId(band, content);
                BY_ID.put(id, registrar.item(REGISTRY_NAMESPACE, id,
                        () -> new gregtech.content.item.WoodenBucketItem(band, content)));
            }
    }

    private static void registerPaintSprays(ContentRegistrar registrar) {
        for (var dye : gregtech.content.tool.PaintingRules.DYES) {
            BY_ID.put(dye.fullId(), registrar.item(REGISTRY_NAMESPACE, dye.fullId(),
                    () -> new gregtech.content.item.PaintSprayItem(dye, new Item.Properties().stacksTo(1))));
            BY_ID.put(dye.usedId(), registrar.item(REGISTRY_NAMESPACE, dye.usedId(),
                    () -> new gregtech.content.item.PaintSprayItem(dye, new Item.Properties().stacksTo(1))));
        }
    }
}
