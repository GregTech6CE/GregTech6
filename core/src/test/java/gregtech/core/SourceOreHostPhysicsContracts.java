    private static void absent(String host, Mode mode) {
        checks++;
        if (SourceOreHostPhysics.lookup(host, mode, 2).isPresent())
            throw new AssertionError("Unexpected known binding: " + host + "/" + mode);
    }
    private static void expect(String host, Mode mode, int quality, float hardness, float resistance,
                               int harvest, String tool) {
        checks++;
        var actual = SourceOreHostPhysics.lookup(host, mode, quality).orElseThrow();
        // Source literals are floats. Decimal literals here allow at most two float rounding ULPs,
        // not broad numeric approximation (.37 must never become .375).
        if (!close(actual.hardness(), hardness) || !close(actual.resistance(), resistance)
                || actual.harvest() != harvest || !actual.tool().equals(tool)
                    || actual.requiresToolForDrops() == tool.equals("SHOVEL"))
            throw new AssertionError(host + "/" + mode + "/" + quality + ": " + actual
                    + " expected H=" + hardness + " R=" + resistance + " level=" + harvest + " tool=" + tool);
    }
    private static boolean close(float actual, float expected) {
        return Float.isFinite(actual) && Math.abs(actual - expected) <= 2 * Math.ulp(expected);
    }
