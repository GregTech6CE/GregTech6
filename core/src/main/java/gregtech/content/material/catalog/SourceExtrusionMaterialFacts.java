    private static Map.Entry<Integer, Row> row(int id, String name, Profile profile) {
        return Map.entry(id, new Row(name, profile));
    }

    public static MaterialDefinition.Declaration apply(MaterialDefinition.Declaration declaration) {
        Row row = ROWS.get(declaration.id());
        if (row == null || !sameName(row.name(), declaration.name())) return declaration;
        var info = declaration.info();
        var rules = new LinkedHashMap<>(info.processes().rules());
        MaterialFactKeys.put(
                rules, MaterialFactKeys.SOURCE_EXTRUSION, List.of(MaterialProcessRule.anyForm(row.profile())));
        return new MaterialDefinition.Declaration(
                declaration.material(),
                new MaterialInfoDefinition(
                        info.tooling(),
                        info.composition(),
                        info.relations(),
                        new MaterialInfoDefinition.Processes(rules)));
    }

    /** The source list spells e.g. {@code SpaceStone} where the port spells {@code Space Stone}. */
    private static boolean sameName(String source, String port) {
        if (source.equals(port)) return true;
        return source.replaceAll("[^A-Za-z0-9]", "").equalsIgnoreCase(port.replaceAll("[^A-Za-z0-9]", ""));
    }
