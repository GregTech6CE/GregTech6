    private static Entry entry(
            String id,
            GTMaterial material,
            BurningBoxFuelType type,
            int efficiency,
            long output,
            float hardness,
            float resistance) {
        String texture = switch (type) {
            case SOLID -> "burning_solid";
            case LIQUID -> "burning_liquid";
            case GAS -> "burning_gas";
            case FLUIDIZED_BED -> "burning_fluidbed";
        };
        return new Entry(
                type,
                new MachineSpec(
                        id,
                        material.getLocalName(),
                        material.getColor(),
                        efficiency,
                        output,
                        texture,
                        hardness,
                        resistance));
    }

    public static List<Entry> all() {
        return ALL;
    }

    public static MachineSpec spec(String id) {
        return ALL.stream()
                .filter(e -> e.spec().id().equals(id))
                .findFirst()
                .orElseThrow(() -> new IllegalArgumentException(id))
                .spec();
    }
