#!/usr/bin/env python3
"""Check source comments for stale or unreadable code references.

Findings:
  repo-line-ref   line number into this repository's own code (drifts every edit)
  bare-line-ref   ":123" with no file to look it up in
  unknown-line-ref  "Foo.java:123" whose file is neither in this repo nor upstream
  history         comments about batches/changes instead of the current code

Usage:
  python tools/comments/check_comment_refs.py [--upstream PATH] [--json] [--strict]

--upstream  a checkout of the GT6 tree at the commit pinned in AGENTS.md;
            enabled line numbers are checked against that file's length.
Exit code is 1 when any finding is reported (generated sources are listed but do
not fail, since their generators are not in this tree).
"""
import argparse
import json
import os
import re
import sys

SOURCE_ROOTS = [
    "core/src",
    "minecraft/src",
    "minecraft/versions/1.20.1-forge/src",
    "minecraft/versions/1.21.1-neoforge/src",
]

LINE_REF = re.compile(
    r"(?<![\w])(?:(?P<owner>(?:[\w.-]+/)*[A-Za-z_][\w.$]*?)(?:\.java)?)?"
    r":(?P<line>\d+)(?:\s*[-–]\s*(?P<end>\d+))?"
)
HISTORY = re.compile(
    r"\b(this batch|this change|before this batch|before this change|previous version|"
    r"earlier version|used to (?:be|do|have)|no longer (?:needs|does|is)|"
    r"was (?:added|removed|renamed)|earlier import)\b",
    re.I,
)
GENERATED = re.compile(r"GENERATED by|do not edit by hand|DO NOT EDIT")


def iter_comments(text):
    """Yield (line, comment text) for every // and /* */ comment outside literals."""
    i, n, line = 0, len(text), 1
    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
            i += 1
        elif text.startswith('"""', i):
            j = text.find('"""', i + 3)
            if j < 0:
                return
            line += text.count("\n", i, j + 3)
            i = j + 3
        elif c in "\"'":
            quote = c
            i += 1
            while i < n and text[i] != quote:
                if text[i] == "\\":
                    i += 1
                elif text[i] == "\n" and quote == "'":
                    break
                i += 1
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            yield line, text[i:j]
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            yield line, text[i:j]
            line += text.count("\n", i, j)
            i = j
        else:
            i += 1


def load_repo(root):
    """Map class name -> package for every java file, and package -> class names."""
    classes = {}          # simple name -> set of packages
    packages = {}         # package -> set of simple names
    paths = []
    for base in SOURCE_ROOTS:
        for dirpath, _, filenames in os.walk(os.path.join(root, base)):
            rel = os.path.relpath(dirpath, os.path.join(root, base)).replace("\\", "/")
            pkg = rel.split("java/")[-1].replace("/", ".")
            for f in filenames:
                if f.endswith(".java"):
                    paths.append(os.path.join(dirpath, f))
                    name = f[:-5]
                    classes.setdefault(name, set()).add(pkg)
                    packages.setdefault(pkg, set()).add(name)
    return classes, packages, paths


DECL = re.compile(r"^\s*(?:public\s+|final\s+|abstract\s+)*(?:class|interface|enum|@interface)\s+(\w+)", re.M)


def load_upstream(path):
    """Map each file basename and each declared type name to its line count."""
    files = {}
    for dirpath, dirnames, filenames in os.walk(path):
        dirnames[:] = [d for d in dirnames if d not in (".git", "build", ".gradle")]
        for f in filenames:
            if not f.endswith(".java"):
                continue
            p = os.path.join(dirpath, f)
            try:
                with open(p, encoding="utf-8", errors="replace") as fh:
                    text = fh.read()
            except OSError:
                continue
            lines = text.count("\n") + 1
            files[f] = max(files.get(f, 0), lines)
            for name in DECL.findall(text):
                files[f"{name}#"] = max(files.get(f"{name}#", 0), lines)
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--upstream")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--strict", action="store_true", help="treat history findings as failures")
    args = ap.parse_args()

    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", errors="replace")

    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    repo_classes, repo_packages, paths = load_repo(root)
    upstream = load_upstream(args.upstream) if args.upstream else {}

    findings = []
    for path in paths:
        rel = os.path.relpath(path, root).replace("\\", "/")
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        generated = bool(GENERATED.search(text[:4000]))
        pkg = re.search(r"^package\s+([\w.]+);", text, re.M)
        pkg = pkg.group(1) if pkg else ""
        imports = {i.split(".")[-1] for i in re.findall(r"^import\s+(?:static\s+)?([\w.]+);", text, re.M)}
        local = repo_packages.get(pkg, set()) | imports | {os.path.basename(path)[:-5]}

        for line, body in iter_comments(text):
            if body.lstrip("/* ").startswith("? "):
                continue
            for m in LINE_REF.finditer(body):
                owner = m.group("owner")
                if owner in ("http", "https"):
                    continue
                prev = body[m.start() - 1:m.start()] if m.start() else ""
                if prev in ')\":"' or "pack_format" in body:
                    continue      # commented-out code / JSON payload, not a source reference
                end = int(m.group("end") or m.group("line"))
                if not owner:
                    kind = "bare-line-ref"
                    if generated:
                        continue
                    findings.append((rel, line, kind, m.group(0), body.strip()[:160]))
                    continue
                simple = owner.split("/")[-1].split(".")[-1]
                if "/" in owner and upstream and (simple + ".java" in upstream or simple + "#" in upstream):
                    limit = upstream.get(simple + ".java") or upstream[simple + "#"]
                    if end > limit:
                        findings.append((rel, line, "upstream-line-out-of-range", m.group(0),
                                         body.strip()[:160]))
                    continue
                if simple in local:
                    kind = "repo-line-ref"
                elif simple in repo_classes and pkg in repo_classes[simple]:
                    kind = "repo-line-ref"
                elif simple in repo_classes and len(repo_classes[simple]) == 1 and simple not in upstream:
                    kind = "repo-line-ref"
                elif upstream and (simple + ".java" in upstream or simple + "#" in upstream):
                    limit = upstream.get(simple + ".java") or upstream[simple + "#"]
                    if end > limit:
                        kind = "upstream-line-out-of-range"
                    else:
                        continue
                else:
                    kind = "unknown-line-ref"
                if generated:
                    kind += " (generated)"
                findings.append((rel, line, kind, m.group(0), body.strip()[:160]))

            if HISTORY.search(body):
                findings.append((rel, line, "history", HISTORY.search(body).group(0),
                                 body.strip()[:160]))

    order = {"repo-line-ref": 0, "bare-line-ref": 1, "unknown-line-ref": 2,
             "upstream-line-out-of-range": 3, "history": 4}
    findings.sort(key=lambda f: (f[0], f[1]))

    if args.json:
        json.dump([dict(zip(("file", "line", "kind", "ref", "text"), f)) for f in findings],
                  sys.stdout, ensure_ascii=False, indent=1)
        sys.stdout.write("\n")
    else:
        for rel, line, kind, ref, text in findings:
            print(f"{rel}:{line}: {kind}: {ref}  | {text}")

    failures = [f for f in findings
                if not f[2].startswith("history") and "(generated)" not in f[2]]
    history = [f for f in findings if f[2] == "history"]
    print(f"\n{len(findings)} findings: " +
          ", ".join(f"{k}={sum(1 for f in findings if f[2].startswith(k))}" for k in order),
          file=sys.stderr)
    sys.stderr.write(f"{len(failures)} reference findings, {len(history)} history findings\n")
    if failures or (args.strict and history):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
