#!/usr/bin/env python3
"""Check source comments against the repository comment standard.

Findings:
  line-ref        Foo.java:123, Loader_X:123, line 123, at :123, tick():123
  history         comments about batches/changes instead of the current code
  unknown-symbol  {Class#member} / {Class.member(...)} missing under --upstream

Modes:
  (default)       every Java file under the source roots
  --diff RANGE    added lines in a git diff range, for CI

Data tables (a ``generated`` directory, a GENERATED header, or a file marked with
``// source-rows``) may keep per-row upstream line numbers; their line-ref findings
are listed but do not fail.
Exit code is 1 when a non-generated file has a line-ref or history finding.
"""
import argparse
import json
import os
import re
import subprocess
import sys

SOURCE_ROOTS = [
    "core/src",
    "minecraft/src",
    "minecraft/versions/1.20.1-forge/src",
    "minecraft/versions/1.21.1-neoforge/src",
]

LINE_REF = re.compile(
    r"(?<![\w])(?:(?P<owner>(?:[\w.-]+/)*[A-Za-z_][\w.$]*?)(?:\.java)?)?"
    r":(?P<line>\d+)(?:\s*[-–]\s*(?P<end>\d+))?"
)
EXTRA_REFS = [
    (re.compile(r"\blines?\s+\d+(?:\s*[-–]\s*\d+)?", re.I), "line number"),
    (re.compile(r"\bat\s+:\s*\d+"), "bare line number"),
    (re.compile(r"\(\):\s*\d{2,}"), "method line number"),
]
HISTORY = re.compile(
    r"本批次|本卡|计划卡|card-plans|之前是|"
    r"\b(this batch|this change|before this batch|before this change|previous version|"
    r"earlier version|used to (?:be|do|have)|no longer (?:needs|does|is)|"
    r"was (?:added|removed|renamed)|earlier import)\b",
    re.I,
)
SYMBOL = re.compile(r"\{@code\s+([A-Z][\w$]*)[#.]([\w$]+)")
GENERATED_PATH = re.compile(r"(^|/)generated(/|$)")
GENERATED_HEADER = re.compile(r"GENERATED by|do not edit by hand|DO NOT EDIT")
SOURCE_ROWS = re.compile(r"(?m)^\s*(?:\*|//)\s*source-rows\b")
COMMENT_START = ("//", "*", "/*")

UPSTREAM_TEXT = {}
DATA_TABLE_CACHE = {}


def is_data_table(path):
    """A generated file or a hand-written table marked with ``// source-rows``."""
    cached = DATA_TABLE_CACHE.get(path)
    if cached is None:
        try:
            with open(path, encoding="utf-8", errors="replace") as handle:
                header = handle.read(4000)
        except OSError:
            header = ""
        cached = bool(GENERATED_HEADER.search(header) or SOURCE_ROWS.search(header))
        DATA_TABLE_CACHE[path] = cached
    return cached


def iter_comments(text):
    """Yield (line, comment text) for every // and /* */ comment outside literals."""
    i, n, line = 0, len(text), 1
    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
            i += 1
        elif text.startswith('"""', i):
            j = text.find('"""', i + 3)
            if j < 0:
                return
            line += text.count("\n", i, j + 3)
            i = j + 3
        elif c in "\"'":
            quote = c
            i += 1
            while i < n and text[i] != quote:
                if text[i] == "\\":
                    i += 1
                elif text[i] == "\n" and quote == "'":
                    break
                i += 1
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            yield line, text[i:j]
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            yield line, text[i:j]
            line += text.count("\n", i, j)
            i = j
        else:
            i += 1


def load_upstream(root):
    """Map each upstream class name to its source file."""
    index = {}
    for directory, _, names in os.walk(root):
        if ".git" in directory or "build" in directory or ".gradle" in directory:
            continue
        for name in names:
            if name.endswith(".java"):
                index.setdefault(name[:-5], os.path.join(directory, name))
    return index


def upstream_has_member(path, member):
    text = UPSTREAM_TEXT.get(path)
    if text is None:
        with open(path, encoding="utf-8", errors="replace") as handle:
            text = handle.read()
        UPSTREAM_TEXT[path] = text
    return re.search(r"\b" + re.escape(member) + r"\b", text) is not None


def check_comment(rel, line, body, generated, upstream):
    findings = []
    seen = set()
    for match in LINE_REF.finditer(body):
        owner = match.group("owner")
        if owner in ("http", "https"):
            continue
        prev = body[match.start() - 1] if match.start() else ""
        if prev in ')\\":' or "pack_format" in body:
            continue
        if owner:
            simple = owner.split("/")[-1].split(".")[-1]
            if not simple[:1].isupper():
                continue
        else:
            if prev.isdigit() or "://" in body[max(0, match.start() - 8):match.start()]:
                continue
        ref = match.group(0)
        if ref in seen:
            continue
        seen.add(ref)
        findings.append((rel, line, "line-ref", ref, body.strip()[:160]))
    for pattern, label in EXTRA_REFS:
        match = pattern.search(body)
        if match and match.group(0) not in seen:
            seen.add(match.group(0))
            findings.append((rel, line, "line-ref", match.group(0), body.strip()[:160]))
    match = HISTORY.search(body)
    if match:
        findings.append((rel, line, "history", match.group(0), body.strip()[:160]))
    if upstream is not None:
        for match in SYMBOL.finditer(body):
            owner, member = match.group(1), match.group(2)
            source = upstream.get(owner)
            if source is None:
                findings.append((rel, line, "unknown-symbol", f"{owner}#{member}", body.strip()[:160]))
            elif not upstream_has_member(source, member):
                findings.append((rel, line, "unknown-symbol", f"{owner}#{member}", body.strip()[:160]))
    if generated:
        findings = [(f, i, k + " (data table)", r, t) for f, i, k, r, t in findings if k != "unknown-symbol"]
    return findings


def is_comment(line):
    return line.lstrip().startswith(COMMENT_START)


def scan_files(root, upstream):
    findings = []
    for base in SOURCE_ROOTS:
        for directory, _, names in os.walk(os.path.join(root, base)):
            for name in names:
                if not name.endswith(".java"):
                    continue
                path = os.path.join(directory, name)
                rel = os.path.relpath(path, root).replace(os.sep, "/")
                with open(path, encoding="utf-8", errors="replace") as handle:
                    text = handle.read()
                generated = bool(GENERATED_PATH.search(rel) or is_data_table(path))
                for line, body in iter_comments(text):
                    if body.lstrip("/* ").startswith("? "):
                        continue
                    findings.extend(check_comment(rel, line, body, generated, upstream))
    return findings


def scan_diff(root, revision_range, upstream):
    result = subprocess.run(
        ["git", "diff", "--unified=0", "--diff-filter=AM", revision_range, "--", "*.java"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(result.stderr.strip() or "git diff failed")
    findings = []
    path = None
    number = 0
    for line in result.stdout.splitlines():
        if line.startswith("+++ b/"):
            path = line[6:]
            continue
        if line.startswith("@@"):
            match = re.search(r"\+(\d+)", line)
            number = int(match.group(1)) if match else 0
            continue
        if path is None or GENERATED_PATH.search(path) or is_data_table(path):
            continue
        if line.startswith("+") and not line.startswith("+++"):
            text = line[1:]
            if is_comment(text):
                findings.extend(check_comment(path, number, text, False, upstream))
            number += 1
        elif line.startswith(" "):
            number += 1
    return findings


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", help="GT6 source tree at the pinned commit, enables symbol checks")
    parser.add_argument("--diff", metavar="RANGE", help="check added lines in a git diff range")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", errors="replace")

    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    upstream = load_upstream(args.upstream) if args.upstream else None
    findings = scan_diff(root, args.diff, upstream) if args.diff else scan_files(root, upstream)
    findings.sort(key=lambda finding: (finding[0], finding[1]))

    if args.json:
        json.dump(
            [dict(zip(("file", "line", "kind", "ref", "text"), finding)) for finding in findings],
            sys.stdout,
            ensure_ascii=False,
            indent=1,
        )
        sys.stdout.write("\n")
    else:
        for rel, line, kind, ref, text in findings:
            print(f"{rel}:{line}: {kind}: {ref}  | {text}")

    failures = [f for f in findings if f[2] in ("line-ref", "history")]
    warnings = [f for f in findings if f[2] == "unknown-symbol"]
    generated = [f for f in findings if f[2].endswith("(generated)")]
    print(
        f"{len(failures)} failure(s), {len(warnings)} symbol warning(s), "
        f"{len(generated)} data-table finding(s)",
        file=sys.stderr,
    )
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
